-- BUSINESS RECOMMENDATIONS
-- based on everything found in the EDA, advanced SQL queries, and insights above

-- 1. Fix Furniture's profitability
-- Furniture brought in 127,181 in sales but only 2,298 profit (1.81% margin) - the
-- lowest of the 3 categories. worth reviewing pricing, discounting, and supplier
-- costs for this category specifically before pushing more sales into it.

-- 2. Investigate the loss-making states
-- Tamil Nadu (-2,216), Punjab, Andhra Pradesh, and Bihar all ended up in the red.
-- since West Bengal proves a state can run a high margin without huge sales volume,
-- these states are worth a deeper look into what's different about their costs/pricing.

-- 3. Review unprofitable customers, not just top spenders
-- Pooja generated 9,030 in sales but still lost money overall (-269 profit).
-- high sales from a customer doesn't automatically mean they're a "good" customer -
-- worth checking if heavy discounting or high-return products are behind cases like this.

-- 4. Address the target miss in Clothing
-- Clothing came in 78.71% below its target in July 2018, the biggest gap found in the
-- whole target vs actual comparison. worth checking if this was a one-off (stock
-- issue, seasonal dip) or a pattern that shows up in other months too.

-- 5. Focus on margin, not just top-line sales
-- Electronics sells the most but Clothing is actually more profitable per rupee sold.
-- growth strategy shouldn't just chase sales volume - protecting/improving margin
-- matters just as much, especially in categories like Furniture that are close to break-even.
